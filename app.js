let currentLang = 'en';
let selectedImages = [];

function getUserId() {
    let id = localStorage.getItem('bscmg_user_id');
    if (!id) {
        id = 'user_' + Date.now() + '_' + Math.random().toString(36).substr(2, 9);
        localStorage.setItem('bscmg_user_id', id);
    }
    return id;
}

function changeLanguage(lang) {
    currentLang = lang;
    localStorage.setItem('bscmg_lang', lang);
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
    const t = translations[lang] || translations.en;
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (t[key]) el.textContent = t[key];
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (t[key]) el.placeholder = t[key];
    });
}

function loadApplications() {
    try { return JSON.parse(localStorage.getItem('bscmg_applications') || '[]'); }
    catch { return []; }
}

function saveApplications(apps) {
    localStorage.setItem('bscmg_applications', JSON.stringify(apps));
}

function switchTab(name) {
    document.querySelectorAll('.panel').forEach(p => p.classList.remove('active'));
    document.querySelectorAll('.nav-link').forEach(b => b.classList.remove('active'));
    const panel = document.getElementById('tab-' + name);
    if (panel) panel.classList.add('active');
    document.querySelectorAll('.nav-link').forEach(b => {
        if (b.dataset.tab === name) b.classList.add('active');
    });
}

function checkUserStatus() {
    const userId = getUserId();
    const apps = loadApplications();
    const myApp = apps.find(a => a.userId === userId);
    const statusSection = document.getElementById('statusSection');
    const applySection = document.getElementById('applySection');
    const statusCard = document.getElementById('statusCard');
    const t = translations[currentLang] || translations.en;

    if (!myApp) {
        statusSection.style.display = 'none';
        if (applySection) applySection.style.display = 'block';
        return;
    }

    statusSection.style.display = 'block';

    if (myApp.status === 'accepted') {
        if (applySection) applySection.style.display = 'none';
        statusCard.className = 'status-card accepted';
        statusCard.innerHTML = `
            <h2>${t.acceptedTitle}</h2>
            <p>${t.acceptedMsg}</p>
            <a href="https://discord.gg/gwqxWPZSkt" target="_blank" class="invite-link">discord.gg/gwqxWPZSkt</a>
        `;
        switchTab('about');
    } else if (myApp.status === 'declined') {
        if (applySection) applySection.style.display = 'none';
        statusCard.className = 'status-card declined';
        statusCard.innerHTML = `
            <h2>${t.declinedTitle}</h2>
            <p>${t.declinedMsg}</p>
        `;
        switchTab('about');
    } else {
        if (applySection) applySection.style.display = 'none';
        statusCard.className = 'status-card';
        statusCard.innerHTML = `
            <h2>${t.pendingTitle}</h2>
            <p>${t.pendingMsg}</p>
        `;
        switchTab('about');
    }
}

const uploadArea = document.getElementById('uploadArea');
const fileInput = document.getElementById('images');
const previewContainer = document.getElementById('previewContainer');

if (uploadArea) {
    uploadArea.addEventListener('dragover', e => {
        e.preventDefault();
        uploadArea.classList.add('dragover');
    });
    uploadArea.addEventListener('dragleave', () => uploadArea.classList.remove('dragover'));
    uploadArea.addEventListener('drop', e => {
        e.preventDefault();
        uploadArea.classList.remove('dragover');
        handleFiles(e.dataTransfer.files);
    });
}
if (fileInput) {
    fileInput.addEventListener('change', e => handleFiles(e.target.files));
}

function handleFiles(files) {
    const remaining = 3 - selectedImages.length;
    Array.from(files).slice(0, remaining).forEach(file => {
        if (!file.type.startsWith('image/')) return;
        if (file.size > 2 * 1024 * 1024) {
            alert('Image too large (max 2MB)');
            return;
        }
        const reader = new FileReader();
        reader.onload = e => {
            selectedImages.push({ name: file.name, data: e.target.result });
            renderPreviews();
        };
        reader.readAsDataURL(file);
    });
}

function renderPreviews() {
    if (!previewContainer) return;
    previewContainer.innerHTML = '';
    selectedImages.forEach((img, index) => {
        const div = document.createElement('div');
        div.className = 'preview-item';
        div.innerHTML = `<img src="${img.data}" alt=""><button type="button" class="remove-btn" onclick="removeImage(${index})">×</button>`;
        previewContainer.appendChild(div);
    });
}

function removeImage(index) {
    selectedImages.splice(index, 1);
    renderPreviews();
}

document.getElementById('applicationForm').addEventListener('submit', e => {
    e.preventDefault();
    const userId = getUserId();
    const apps = loadApplications();
    if (apps.find(a => a.userId === userId)) {
        alert((translations[currentLang] || translations.en).alreadySubmitted);
        return;
    }
    const application = {
        id: 'app_' + Date.now() + '_' + Math.random().toString(36).substr(2, 6),
        userId,
        q1: document.getElementById('q1').value.trim(),
        q2: document.getElementById('q2').value.trim(),
        q3: document.getElementById('q3').value.trim(),
        discord: document.getElementById('q4').value.trim(),
        shredderDesc: document.getElementById('shredderDesc').value.trim(),
        images: selectedImages.map(i => i.data),
        status: 'pending',
        createdAt: new Date().toISOString(),
        updatedAt: new Date().toISOString()
    };
    apps.push(application);
    saveApplications(apps);
    alert((translations[currentLang] || translations.en).submitSuccess);
    checkUserStatus();
    document.getElementById('applicationForm').reset();
    selectedImages = [];
    renderPreviews();
});

